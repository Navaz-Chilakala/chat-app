/**
 * Deterministic, template-based code generation from parsed OpenAPI operations and schemas.
 * No LLM: output is fully reproducible from the indexed schema version. Generated code includes input
 * validation, timeouts and RFC 7807 ProblemDetails error handling, plus a provenance header.
 */

type Json = Record<string, unknown>;
const obj = (v: unknown): Json => (v && typeof v === "object" && !Array.isArray(v) ? (v as Json) : {});

export interface OpInput {
  method: string;
  path: string;
  operationId: string | null;
  summary: string | null;
  parameters: Json[];
  requestBody: Json | null;
  responses: Json;
}

export interface GenInput {
  apiTitle: string;
  apiVersion: string | null;
  specRefs: string[];
  sourceLabel: string;
  operations: OpInput[];
  schemas: { name: string; schema: Json }[];
}

export interface GeneratedFile {
  path: string;
  language: string;
  content: string;
}

export type Target = "typescript-client" | "python-client" | "python-fastapi" | "go-structs";

const IDENT_RE = /[^A-Za-z0-9_]/g;
export function pascal(s: string): string {
  const out = s.replace(/[^A-Za-z0-9]+(.)?/g, (_, c: string | undefined) => (c ? c.toUpperCase() : "")).replace(/^[a-z]/, (c) => c.toUpperCase());
  return /^[0-9]/.test(out) ? `T${out}` : out || "Unnamed";
}
export function camel(s: string): string {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
}
export function snake(s: string): string {
  return s.replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2").replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").toLowerCase() || "x";
}
function opName(op: OpInput): string {
  return op.operationId ? op.operationId.replace(IDENT_RE, "_") : `${op.method.toLowerCase()}${pascal(op.path)}`;
}
function refName(ref: string): string {
  return pascal(ref.split("/").pop() ?? "Unknown");
}
function header(g: GenInput, comment: string): string {
  return [
    `${comment} Generated by Telecom Knowledge AI (deterministic template, no LLM).`,
    `${comment} API: ${g.apiTitle}${g.apiVersion ? ` ${g.apiVersion}` : ""} — source: ${g.sourceLabel}`,
    g.specRefs.length ? `${comment} Normative behaviour: ${g.specRefs.join("; ")} (the schema alone does not define procedure semantics).` : `${comment} No 3GPP spec reference found in the OpenAPI document.`,
    `${comment} Review before use. External $refs (e.g. TS29571_CommonData) are typed as unknown.`,
  ].join("\n");
}

// ---------------- TypeScript ----------------
function tsType(s: unknown, depth = 0): string {
  const o = obj(s);
  if (typeof o.$ref === "string") return o.$ref.startsWith("#/") ? refName(o.$ref) : "unknown /* external ref */";
  if (Array.isArray(o.allOf)) return o.allOf.map((x) => tsType(x, depth + 1)).join(" & ") || "unknown";
  if (Array.isArray(o.oneOf) || Array.isArray(o.anyOf)) return ((o.oneOf ?? o.anyOf) as unknown[]).map((x) => tsType(x, depth + 1)).join(" | ") || "unknown";
  if (Array.isArray(o.enum)) return o.enum.map((e) => JSON.stringify(e)).join(" | ") || "never";
  const nullable = o.nullable ? " | null" : "";
  switch (o.type) {
    case "string": return `string${nullable}`;
    case "integer":
    case "number": return `number${nullable}`;
    case "boolean": return `boolean${nullable}`;
    case "array": return `Array<${tsType(o.items, depth + 1)}>${nullable}`;
    case "object": {
      const props = obj(o.properties);
      if (!Object.keys(props).length || depth > 2) return o.additionalProperties ? `Record<string, ${o.additionalProperties === true ? "unknown" : tsType(o.additionalProperties, depth + 1)}>` : "Record<string, unknown>";
      const req = new Set(Array.isArray(o.required) ? o.required.map(String) : []);
      return `{ ${Object.entries(props).map(([k, v]) => `${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${tsType(v, depth + 1)}`).join("; ")} }`;
    }
    default: return "unknown";
  }
}

function genTsClient(g: GenInput): GeneratedFile[] {
  const lines: string[] = [header(g, "//"), ""];
  lines.push(
    "export interface ProblemDetails { type?: string; title?: string; status?: number; detail?: string; instance?: string; cause?: string; invalidParams?: unknown[]; [key: string]: unknown }",
    "",
    "export class ApiError extends Error {",
    "  constructor(public readonly status: number, public readonly problem: ProblemDetails | null, message: string) {",
    "    super(message);",
    '    this.name = "ApiError";',
    "  }",
    "}",
    "",
  );
  for (const s of g.schemas) {
    const o = obj(s.schema);
    if (o.type === "object" || o.properties) {
      const props = obj(o.properties);
      const req = new Set(Array.isArray(o.required) ? o.required.map(String) : []);
      if (o.description) lines.push(`/** ${String(o.description).replace(/\*\//g, "").slice(0, 300)} */`);
      lines.push(`export interface ${pascal(s.name)} {`);
      for (const [k, v] of Object.entries(props)) lines.push(`  ${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${tsType(v, 1)};`);
      if (o.additionalProperties) lines.push("  [key: string]: unknown;");
      lines.push("}", "");
    } else lines.push(`export type ${pascal(s.name)} = ${tsType(o)};`, "");
  }
  const cls = `${pascal(g.apiTitle)}Client`;
  lines.push(
    "export interface ClientOptions {",
    "  /** API root including the apiRoot/apiName/apiVersion prefix, e.g. https://nrf.example.com/nnrf-nfm/v1 */",
    "  baseUrl: string;",
    "  accessToken?: () => string | Promise<string>;",
    "  headers?: Record<string, string>;",
    "  timeoutMs?: number;",
    "  fetch?: typeof fetch;",
    "}",
    "",
    `export class ${cls} {`,
    "  private readonly baseUrl: string;",
    "  constructor(private readonly opts: ClientOptions) {",
    '    if (!/^https?:\\/\\//.test(opts.baseUrl)) throw new Error("baseUrl must be an http(s) URL");',
    '    this.baseUrl = opts.baseUrl.replace(/\\/$/, "");',
    "  }",
    "",
    "  private async request<T>(method: string, path: string, query?: Record<string, unknown>, body?: unknown, headers?: Record<string, string>): Promise<T> {",
    "    const url = new URL(this.baseUrl + path);",
    "    for (const [k, v] of Object.entries(query ?? {})) {",
    "      if (v === undefined || v === null) continue;",
    "      url.searchParams.set(k, typeof v === \"object\" ? JSON.stringify(v) : String(v));",
    "    }",
    "    const h: Record<string, string> = { accept: \"application/json, application/problem+json\", ...(this.opts.headers ?? {}), ...(headers ?? {}) };",
    "    if (body !== undefined) h[\"content-type\"] = \"application/json\";",
    "    if (this.opts.accessToken) h.authorization = `Bearer ${await this.opts.accessToken()}`;",
    "    const controller = new AbortController();",
    "    const timer = setTimeout(() => controller.abort(), this.opts.timeoutMs ?? 10_000);",
    "    try {",
    "      const res = await (this.opts.fetch ?? fetch)(url, { method, headers: h, body: body === undefined ? undefined : JSON.stringify(body), signal: controller.signal });",
    "      const text = await res.text();",
    "      const data = text ? (JSON.parse(text) as unknown) : undefined;",
    "      if (!res.ok) {",
    "        const problem = data && typeof data === \"object\" ? (data as ProblemDetails) : null;",
    "        throw new ApiError(res.status, problem, `${method} ${path} failed with HTTP ${res.status}${problem?.cause ? ` (${problem.cause})` : \"\"}`);",
    "      }",
    "      return data as T;",
    "    } finally {",
    "      clearTimeout(timer);",
    "    }",
    "  }",
  );
  for (const op of g.operations) {
    const params = op.parameters.map(obj);
    const pathP = params.filter((p) => p.in === "path");
    const queryP = params.filter((p) => p.in === "query");
    const headerP = params.filter((p) => p.in === "header");
    const bodySchema = obj(obj(obj(op.requestBody).content)["application/json"]).schema;
    const okCode = Object.keys(op.responses).find((c) => /^2/.test(c));
    const okSchema = okCode ? obj(obj(obj(obj(op.responses)[okCode]).content)["application/json"]).schema : undefined;
    const ret = okSchema ? tsType(okSchema) : "void";
    const fields: string[] = [];
    for (const p of [...pathP, ...queryP, ...headerP]) fields.push(`${JSON.stringify(String(p.name))}${p.required ? "" : "?"}: ${p.schema ? tsType(p.schema) : "string"}`);
    if (bodySchema) fields.push(`body${obj(op.requestBody).required ? "" : "?"}: ${tsType(bodySchema)}`);
    const name = camel(opName(op));
    lines.push("", `  /** ${op.method} ${op.path}${op.summary ? ` — ${op.summary.replace(/\*\//g, "").slice(0, 200)}` : ""} */`);
    lines.push(`  async ${name}(params: { ${fields.join("; ")} }${fields.some((f) => !f.includes("?:")) ? "" : " = {}"}): Promise<${ret}> {`);
    for (const p of [...pathP, ...queryP, ...headerP].filter((x) => x.required)) {
      lines.push(`    if (params[${JSON.stringify(String(p.name))}] === undefined || params[${JSON.stringify(String(p.name))}] === null) throw new Error(${JSON.stringify(`Missing required ${String(p.in)} parameter '${String(p.name)}'`)});`);
    }
    if (bodySchema && obj(op.requestBody).required) lines.push(`    if (params.body === undefined) throw new Error("Missing required request body");`);
    let pathExpr = JSON.stringify(op.path);
    for (const p of pathP) pathExpr = `${pathExpr}.replace(${JSON.stringify(`{${String(p.name)}}`)}, encodeURIComponent(String(params[${JSON.stringify(String(p.name))}])))`;
    const q = queryP.length ? `{ ${queryP.map((p) => `${JSON.stringify(String(p.name))}: params[${JSON.stringify(String(p.name))}]`).join(", ")} }` : "undefined";
    const hd = headerP.length ? `Object.fromEntries(Object.entries({ ${headerP.map((p) => `${JSON.stringify(String(p.name))}: params[${JSON.stringify(String(p.name))}]`).join(", ")} }).filter(([, v]) => v !== undefined).map(([k, v]) => [k, String(v)]))` : "undefined";
    lines.push(`    return this.request<${ret}>(${JSON.stringify(op.method.toUpperCase())}, ${pathExpr}, ${q}, ${bodySchema ? "params.body" : "undefined"}, ${hd});`);
    lines.push("  }");
  }
  lines.push("}", "");
  const errorCodes = [...new Set(g.operations.flatMap((o) => Object.keys(o.responses).filter((c) => /^[45]/.test(c))))].sort();
  const readme = [
    `# ${g.apiTitle} TypeScript client`,
    "",
    "Generated deterministically from the indexed OpenAPI document. Requires Node 18+ (global fetch) or pass `fetch`.",
    "",
    "```ts",
    `import { ${cls}, ApiError } from "./client";`,
    `const api = new ${cls}({ baseUrl: "https://nf.example.com/<apiRoot>", accessToken: () => process.env.TOKEN! });`,
    "try { /* await api.<operation>({...}) */ } catch (e) { if (e instanceof ApiError) console.error(e.status, e.problem?.cause); }",
    "```",
    "",
    `Operations: ${g.operations.length}. Error responses declared: ${errorCodes.join(", ") || "none"}.`,
    g.specRefs.length ? `Behavioural requirements are in ${g.specRefs.join("; ")}.` : "",
  ].join("\n");
  return [
    { path: "client.ts", language: "typescript", content: lines.join("\n") },
    { path: "README.md", language: "markdown", content: readme },
  ];
}

// ---------------- Python ----------------
function pyType(s: unknown): string {
  const o = obj(s);
  if (typeof o.$ref === "string") return o.$ref.startsWith("#/") ? `"${refName(o.$ref)}"` : "Any";
  if (Array.isArray(o.enum)) return "str" + (o.nullable ? " | None" : "");
  switch (o.type) {
    case "string": return "str";
    case "integer": return "int";
    case "number": return "float";
    case "boolean": return "bool";
    case "array": return `list[${pyType(o.items).replace(/"/g, "")}]`;
    case "object": return "dict[str, Any]";
    default: return "Any";
  }
}

function genPyClient(g: GenInput): GeneratedFile[] {
  const L: string[] = [header(g, "#"), "from __future__ import annotations", "", "from typing import Any, TypedDict", "from urllib.parse import quote", "", "import httpx", "", ""];
  L.push("class ApiError(Exception):", '    """Raised for non-2xx responses; carries RFC 7807 ProblemDetails when present."""', "", "    def __init__(self, status: int, problem: dict[str, Any] | None, message: str) -> None:", "        super().__init__(message)", "        self.status = status", "        self.problem = problem", "", "");
  for (const s of g.schemas) {
    const o = obj(s.schema);
    const props = obj(o.properties);
    if (!Object.keys(props).length) continue;
    const req = new Set(Array.isArray(o.required) ? o.required.map(String) : []);
    L.push(`class ${pascal(s.name)}(TypedDict, total=False):`);
    if (req.size) L.push(`    """Required: ${[...req].join(", ")}"""`);
    for (const [k, v] of Object.entries(props)) if (/^[A-Za-z_]\w*$/.test(k)) L.push(`    ${k}: ${pyType(v)}`);
    L.push("", "");
  }
  const cls = `${pascal(g.apiTitle)}Client`;
  L.push(
    `class ${cls}:`,
    `    def __init__(self, base_url: str, token: str | None = None, timeout: float = 10.0, client: httpx.Client | None = None) -> None:`,
    '        if not base_url.startswith(("http://", "https://")):',
    '            raise ValueError("base_url must be an http(s) URL")',
    '        self._base = base_url.rstrip("/")',
    '        headers = {"accept": "application/json, application/problem+json"}',
    "        if token:",
    '            headers["authorization"] = f"Bearer {token}"',
    "        self._client = client or httpx.Client(timeout=timeout, headers=headers)",
    "",
    "    def close(self) -> None:",
    "        self._client.close()",
    "",
    "    def _request(self, method: str, path: str, params: dict[str, Any] | None = None, json: Any = None, headers: dict[str, str] | None = None) -> Any:",
    "        clean = {k: v for k, v in (params or {}).items() if v is not None}",
    "        res = self._client.request(method, self._base + path, params=clean, json=json, headers=headers)",
    "        data = res.json() if res.content else None",
    "        if res.is_error:",
    "            problem = data if isinstance(data, dict) else None",
    '            cause = f" ({problem.get(\'cause\')})" if problem and problem.get("cause") else ""',
    '            raise ApiError(res.status_code, problem, f"{method} {path} failed with HTTP {res.status_code}{cause}")',
    "        return data",
  );
  for (const op of g.operations) {
    const params = op.parameters.map(obj);
    const name = snake(opName(op));
    const args: string[] = [];
    const reqd = params.filter((p) => p.required);
    const opt = params.filter((p) => !p.required);
    const bodySchema = obj(obj(obj(op.requestBody).content)["application/json"]).schema;
    for (const p of reqd) args.push(`${snake(String(p.name))}: ${p.schema ? pyType(p.schema).replace(/"/g, "") : "str"}`);
    if (bodySchema && obj(op.requestBody).required) args.push(`body: ${pyType(bodySchema).replace(/"/g, "")}`);
    for (const p of opt) args.push(`${snake(String(p.name))}: ${p.schema ? pyType(p.schema).replace(/"/g, "") : "str"} | None = None`);
    if (bodySchema && !obj(op.requestBody).required) args.push(`body: ${pyType(bodySchema).replace(/"/g, "")} | None = None`);
    L.push("", `    def ${name}(self${args.length ? `, ${args.join(", ")}` : ""}) -> Any:`, `        """${op.method.toUpperCase()} ${op.path}${op.summary ? ` — ${op.summary.replace(/"""/g, "").slice(0, 200)}` : ""}"""`);
    const path = `f"${op.path.replace(/\{([^}]+)\}/g, (_, n: string) => `{quote(str(${snake(n)}), safe='')}`)}"`;
    for (const p of reqd) if (p.in !== "path") L.push(`        if ${snake(String(p.name))} is None:`, `            raise ValueError("missing required parameter '${String(p.name)}'")`);
    const q = params.filter((p) => p.in === "query").map((p) => `"${String(p.name)}": ${snake(String(p.name))}`);
    const h = params.filter((p) => p.in === "header").map((p) => `"${String(p.name)}": ${snake(String(p.name))}`);
    L.push(`        return self._request("${op.method.toUpperCase()}", ${path}, params={${q.join(", ")}}, json=${bodySchema ? "body" : "None"}, headers={k: str(v) for k, v in {${h.join(", ")}}.items() if v is not None})`);
  }
  L.push("");
  return [{ path: "client.py", language: "python", content: L.join("\n") }];
}

function genFastApi(g: GenInput): GeneratedFile[] {
  const L: string[] = [header(g, "#"), '"""FastAPI server stub: routes and request models only; every handler returns 501 until implemented."""', "from __future__ import annotations", "", "from typing import Any", "", "from fastapi import FastAPI, HTTPException, Request", "from pydantic import BaseModel, ConfigDict", "", `app = FastAPI(title=${JSON.stringify(g.apiTitle)}, version=${JSON.stringify(g.apiVersion ?? "0")})`, "", ""];
  for (const s of g.schemas) {
    const props = obj(obj(s.schema).properties);
    if (!Object.keys(props).length) continue;
    const req = new Set(Array.isArray(obj(s.schema).required) ? (obj(s.schema).required as unknown[]).map(String) : []);
    L.push(`class ${pascal(s.name)}(BaseModel):`, '    model_config = ConfigDict(extra="allow")');
    for (const [k, v] of Object.entries(props)) if (/^[A-Za-z_]\w*$/.test(k)) L.push(`    ${k}: ${pyType(v).replace(/"/g, "") === "Any" ? "Any" : pyType(v).replace(/"[A-Za-z0-9_]+"/g, "dict[str, Any]")}${req.has(k) ? "" : " | None = None"}`);
    L.push("", "");
  }
  L.push("def problem(status: int, title: str, cause: str) -> HTTPException:", '    return HTTPException(status_code=status, detail={"status": status, "title": title, "cause": cause})', "", "");
  for (const op of g.operations) {
    const fpath = op.path.replace(/\{([^}]+)\}/g, (_, n: string) => `{${snake(n)}}`);
    const pathArgs = [...op.path.matchAll(/\{([^}]+)\}/g)].map((m) => `${snake(m[1]!)}: str`);
    L.push(`@app.${op.method.toLowerCase()}(${JSON.stringify(fpath)}${op.operationId ? `, operation_id=${JSON.stringify(op.operationId)}` : ""})`);
    L.push(`async def ${snake(opName(op))}(${[...pathArgs, "request: Request"].join(", ")}) -> Any:`);
    L.push(`    """${op.method.toUpperCase()} ${op.path}${op.summary ? ` — ${op.summary.replace(/"""/g, "").slice(0, 200)}` : ""}"""`);
    L.push(`    raise problem(501, "Not Implemented", "NOT_IMPLEMENTED")`, "", "");
  }
  return [
    { path: "server.py", language: "python", content: L.join("\n") },
    { path: "requirements.txt", language: "text", content: "fastapi>=0.115\nuvicorn>=0.30\npydantic>=2.7\n" },
  ];
}

function goType(s: unknown): string {
  const o = obj(s);
  if (typeof o.$ref === "string") return o.$ref.startsWith("#/") ? `*${refName(o.$ref)}` : "json.RawMessage";
  switch (o.type) {
    case "string": return "string";
    case "integer": return "int64";
    case "number": return "float64";
    case "boolean": return "bool";
    case "array": return `[]${goType(o.items).replace(/^\*/, "")}`;
    case "object": return "map[string]any";
    default: return "json.RawMessage";
  }
}

function genGo(g: GenInput): GeneratedFile[] {
  const L = [header(g, "//"), "package api", "", 'import "encoding/json"', "", "var _ = json.RawMessage{}", ""];
  for (const s of g.schemas) {
    const props = obj(obj(s.schema).properties);
    if (!Object.keys(props).length) continue;
    const req = new Set(Array.isArray(obj(s.schema).required) ? (obj(s.schema).required as unknown[]).map(String) : []);
    L.push(`type ${pascal(s.name)} struct {`);
    for (const [k, v] of Object.entries(props)) L.push(`\t${pascal(k)} ${goType(v)} \`json:"${k}${req.has(k) ? "" : ",omitempty"}"\``);
    L.push("}", "");
  }
  return [{ path: "types.go", language: "go", content: L.join("\n") }];
}

export function generate(g: GenInput, target: Target): GeneratedFile[] {
  switch (target) {
    case "typescript-client": return genTsClient(g);
    case "python-client": return genPyClient(g);
    case "python-fastapi": return genFastApi(g);
    case "go-structs": return genGo(g);
  }
}
